function normalizeRu(text: string): string {
  return text
    .replace(/[«»""]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function translateToken(token: string): string {
  const clean = token.replace(/[^\p{L}\p{N}-]/gu, '');
  if (!clean || !CYRILLIC_RE.test(clean)) return token;
  const direct = WORDS[clean];
  if (direct) return direct;
  // простые окончания: кошки → кошка
  const stem = clean.replace(/(ами|ями|ах|ях|ов|ев|ом|ем|ой|ей|ую|юю|ые|ие|ых|ий|ая|яя|ое|ее|у|ю|а|я|ы|и|е|о)$/u, '');
  if (stem !== clean && WORDS[stem]) return WORDS[stem];
  return '';
}

/**
 * Словарный RU→EN для SD 1.5. Не покрывает всё — остаток кириллицы дожимает LLM в main.cjs.
 */
export function translateRuToEnForSd(raw: string): string {
  let text = normalizeRu(raw);
  if (!containsCyrillic(text)) return raw.trim();

  for (const [ru, en] of [...PHRASES].sort((a, b) => b[0].length - a[0].length)) {
    text = text.replace(new RegExp(ru.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), en);
  }

  const parts = text.split(/[,;]+|\s+(?:и|with)\s+/u).map((p) => p.trim()).filter(Boolean);
  const translated: string[] = [];

  for (const part of parts) {
    if (!containsCyrillic(part)) {
      translated.push(part);
      continue;
    }
    const words = part.split(/\s+/).filter(Boolean);
    const chunk = words.map(translateToken).filter(Boolean);
    if (chunk.length) translated.push(chunk.join(' '));
  }

  const joined = translated.join(', ').replace(/\s+/g, ' ').replace(/,\s*,/g, ',').trim();
  return joined || raw.trim();
}
